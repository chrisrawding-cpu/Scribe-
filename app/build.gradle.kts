// Optional stable signing key. CI writes signing.properties from repository secrets so the
// signing certificate (and therefore the SHA-1 you register in Google Cloud) never changes.
val signingProps = Properties().apply {
    val f = rootProject.file("signing.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val hasStableKey = signingProps.getProperty("storeFile")?.let { rootProject.file(it).exists() } == true

